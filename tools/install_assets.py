#!/usr/bin/env python3
"""
Installs the downloaded CC0 assets into the Godot project with a stable,
readable layout, and writes the asset/license manifest.

Run after tools/fetch_assets.py:
    python3 tools/install_assets.py
"""
import json
import os
import shutil
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STAGE = os.path.join(ROOT, "tools", "_asset_stage")

MODEL_LAYOUT = {
    "fern_02": ("vegetation", "polyhaven_fern_02"),
    "weed_plant_02": ("vegetation", "polyhaven_weed_plant_02"),
    "nettle_plant": ("vegetation", "polyhaven_nettle_plant"),
    "wild_rooibos_bush": ("vegetation", "polyhaven_wild_rooibos_bush"),
    "dead_tree_trunk": ("vegetation", "polyhaven_dead_tree_trunk"),
    "stone_01": ("rocks", "polyhaven_stone_01"),
    "coastal_cliff_01": ("rocks", "polyhaven_coastal_cliff_01"),
    "namaqualand_stones_01": ("rocks", "polyhaven_namaqualand_stones_01"),
    "wooden_barrels_01": ("props", "polyhaven_wooden_barrels_01"),
    "wooden_crate_01": ("props", "polyhaven_wooden_crate_01"),
    "stone_fire_pit": ("props", "polyhaven_stone_fire_pit"),
    "barrel_03": ("props", "polyhaven_barrel_03"),
    "gothic_statue": ("props", "polyhaven_gothic_statue"),
}

TEXTURE_MAP = {
    "grass_ground": "grass",
    "forest_ground_04": "forest",
    "cliff_side": "cliff",
    "gravel_ground_01": "gravel",
    "medieval_wood": "medieval_wood",
    "bark_brown_02": "bark_brown_02",
    "mossy_rock": "mossy_rock",
}

ACG_LAYOUT = {
    "Rock064": "cliff and castle masonry base rock",
    "Planks040": "aged timber, doors, beams",
    "RoofingTiles013A": "village roof tiles",
    "Bricks105": "castle masonry",
    "Plaster001": "village wall plaster",
    "Ground037": "soil and mud",
}

POLYHAVEN_URL = "https://polyhaven.com/a/{}"
MANIFEST_HEADER = """# BTH Asset & License Manifest

All assets in this project are free for commercial use. Nothing was purchased,
no paywalled content is included, and every file below was downloaded from the
source URL listed with it.

Last generated by `tools/install_assets.py` at build time.

| Asset | Source | License | Format / resolution | Used in game |
|---|---|---|---|---|
"""


def copy_tree(src, dst):
    if os.path.isdir(dst):
        shutil.rmtree(dst)
    shutil.copytree(src, dst)


def install():
    rows = []
    manifest_models = {}
    manifest_path = os.path.join(STAGE, "polyhaven_models.json")
    if os.path.exists(manifest_path):
        manifest_models = json.load(open(manifest_path))
    for model_id, (category, folder) in MODEL_LAYOUT.items():
        src = os.path.join(STAGE, "polyhaven", "models", model_id)
        if not os.path.isdir(src):
            continue
        dst = os.path.join(ROOT, "assets", category, folder)
        copy_tree(src, dst)
        size = sum(os.path.getsize(os.path.join(dp, f)) for dp, _, fs in os.walk(dst) for f in fs)
        rows.append((folder, POLYHAVEN_URL.format(model_id), "CC0 1.0",
                     f"glTF + 1K JPG ({size/1e6:.1f} MB)",
                     _model_use(model_id)))

    tex_dst_root = os.path.join(ROOT, "assets", "textures", "terrain")
    os.makedirs(tex_dst_root, exist_ok=True)
    for tex_id, short in TEXTURE_MAP.items():
        src_dir = os.path.join(STAGE, "polyhaven", "textures", tex_id)
        if not os.path.isdir(src_dir):
            continue
        for suffix in ("diff", "nor", "arm"):
            src = os.path.join(src_dir, f"{tex_id}_{suffix}.jpg")
            if os.path.exists(src):
                shutil.copy2(src, os.path.join(tex_dst_root, f"{short}_{suffix}.jpg"))
        rows.append((short, POLYHAVEN_URL.format(tex_id), "CC0 1.0", "1K JPG PBR set",
                     _texture_use(tex_id)))

    # ambientCG zips -> extracted folders.
    for asset_id in ACG_LAYOUT:
        src = os.path.join(STAGE, "ambientcg", asset_id)
        if not os.path.isdir(src):
            continue
        dst = os.path.join(ROOT, "assets", "materials", "ambientcg", asset_id)
        copy_tree(src, dst)
        rows.append((asset_id, f"https://ambientcg.com/view?id={asset_id}", "CC0 1.0",
                     "1K JPG PBR set", ACG_LAYOUT[asset_id]))

    # Extra gravel for cobbles (optional, installed if fetched).
    for extra, use in (("Gravel043", "cobbled yard and bridge deck"),):
        src = os.path.join(STAGE, "ambientcg", extra)
        if os.path.isdir(src):
            copy_tree(src, os.path.join(ROOT, "assets", "materials", "ambientcg", extra))
            rows.append((extra, f"https://ambientcg.com/view?id={extra}", "CC0 1.0",
                         "1K JPG PBR set", use))

    hdri_src = os.path.join(STAGE, "polyhaven", "hdri", "belfast_sunset_puresky_2k.hdr")
    if os.path.exists(hdri_src):
        dst = os.path.join(ROOT, "assets", "hdri")
        os.makedirs(dst, exist_ok=True)
        shutil.copy2(hdri_src, os.path.join(dst, "belfast_sunset_puresky_2k.hdr"))
        rows.append(("Belfast Sunset (pure sky)", "https://polyhaven.com/a/belfast_sunset_puresky",
                     "CC0 1.0", "HDR panorama, 2K",
                     "sky, sun direction and image based reflections"))

    # Generated (original) procedural textures.
    proc = os.path.join(ROOT, "assets", "textures", "procedural")
    for dp, _, fs in os.walk(proc):
        for f in fs:
            rel = os.path.relpath(os.path.join(dp, f), proc)
            rows.append((f"procedural/{rel}", "generated by tools/make_textures.py",
                         "CC0 / project original", "PNG 512",
                         _procedural_use(rel)))

    with open(os.path.join(ROOT, "docs", "ASSET_MANIFEST.md"), "w") as fh:
        fh.write(MANIFEST_HEADER)
        for name, source, lic, fmt, use in rows:
            fh.write(f"| `{name}` | {source} | {lic} | {fmt} | {use} |\n")
        fh.write("""
## Not used, and why

* **Poly Haven `fir_tree_01` / `pine_tree_01` / `pine_sapling_medium`** - the CC0
  glTF exports are 7.8M and 17.4M triangles (457 MB / 905 MB of binary data).
  They are beautiful reference scans but cannot be instanced in a real-time
  forest, so live trees in BTH are procedural two-surface meshes using the
  Poly Haven bark material, and Poly Haven's plants provide the undergrowth.
* **Quaternius Medieval Village MegaKit** - the free tier is distributed through
  itch.io behind a download button that requires an interactive browser session
  (no direct free-tier URL, no API). Nothing could be downloaded legitimately
  from this environment, so the village/castle in BTH is built procedurally to
  the same modular grammar (stone plinth, timber frame, plaster infill, tiled
  gable roof). No paid tier was touched.
* **Quaternius Ultimate Nature Pack** - same itch.io gating; not downloaded.
* **Kenney Nature Kit** - kenney.nl blocks scripted downloads (HTTP 403); its
  files are also available only through the page's JS download endpoint. The
  kit is stylised, so BTH's blockout uses procedural geometry instead.

## License notes

Poly Haven and ambientCG assets are CC0 1.0 Universal: no attribution required,
commercial use permitted, redistribution permitted. Attribution is still
recorded here and in `docs/CREDITS.md` as good practice.
""")


def _model_use(model_id):
    return {
        "fern_02": "understory ferns along forest and river edges",
        "weed_plant_02": "scattered meadow weeds and forest floor detail",
        "nettle_plant": "damp ground plants near water and ruins",
        "wild_rooibos_bush": "dry highland scrub",
        "dead_tree_trunk": "fallen timber in clearings",
        "stone_01": "hero boulders and ruin stones",
        "coastal_cliff_01": "cliff outcrop near the waterfall",
        "namaqualand_stones_01": "stone clusters at the castle and ruins",
        "wooden_barrels_01": "village props",
        "wooden_crate_01": "village props",
        "stone_fire_pit": "camps and village gathering areas",
        "barrel_03": "village props",
        "gothic_statue": "castle courtyard monument",
    }.get(model_id, "environment prop")


def _texture_use(tex_id):
    return {
        "grass_ground": "terrain grass layer + meadow tint",
        "forest_ground_04": "forest floor layer",
        "cliff_side": "cliff rock layer",
        "gravel_ground_01": "roads, trails and river gravel",
        "medieval_wood": "timber beams and doors",
        "bark_brown_02": "tree trunks",
        "mossy_rock": "mossy stone accents",
    }.get(tex_id, "PBR material")


def _procedural_use(rel):
    return {
        "foliage/conifer_branch.png": "conifer foliage cards",
        "foliage/leaf_cluster.png": "broadleaf foliage cards",
        "foliage/grass_tuft.png": "grass tuft cards",
        "water/ripple_nrm.png": "river surface normal map",
        "water/water_streak.png": "waterfall foam streaks",
    }.get(rel.replace(os.sep, "/"), "procedural detail")


if __name__ == "__main__":
    install()
    print("ASSETS_INSTALLED")
